class TestTargetResolutionHDF5:
    """Test target_resolution parameter for HDF5 AMR reader."""

    def test_coarsens_output(self) -> None:
        reader, _ = open_batsrus(AMR_DIR)
        ds = reader.read_timestep(AMR_DIR, 0, target_resolution=1.0)
        assert ds["B_1"].shape == (16, 16)

    def test_none_is_finest(self) -> None:
        reader, _ = open_batsrus(AMR_DIR)
        ds_default = reader.read_timestep(AMR_DIR, 0)
        ds_explicit = reader.read_timestep(AMR_DIR, 0, target_resolution=None)
