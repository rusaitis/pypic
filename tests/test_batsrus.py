class TestFieldMap:
    """Unit tests for field name mapping and unit conversion."""

    def test_canonical_names_cover_mhd_basics(self) -> None:
        assert FIELD_NAME_MAP["Rho"] == "rho_m"
        assert FIELD_NAME_MAP["Bx"] == "B_1"
        assert FIELD_NAME_MAP["Ux"] == "V_1"
        assert FIELD_NAME_MAP["P"] == "P"

    def test_hyp_is_skipped(self) -> None:
        assert "Hyp" in SKIP_FIELDS

    def test_normalized_detection(self) -> None:
        assert is_normalized("normalized units")
        assert is_normalized("  Normalized  ")
        assert not is_normalized("Mp/cc km/s nT")

    @pytest.mark.parametrize(
        ("unit_str", "expected"),
        [
            ("nT", 1e-9),
            ("km/s", 1e3),
            ("nPa", 1e-9),
            ("R", 1.0),
        ],
    )
    def test_unit_factor(self, unit_str: str, expected: float) -> None:
        assert_allclose(unit_factor(unit_str), expected, rtol=1e-10)

    def test_density_to_si(self) -> None:
        from scipy import constants

        factor = unit_factor("Mp/cc")
        rho_mpccc = 5.0
        rho_si = rho_mpccc * factor
        expected = 5.0 * 1e6 * constants.m_p
        assert_allclose(rho_si, expected, rtol=1e-10)

    def test_convert_fields_noop_for_normalized(self) -> None:
        fields = {"rho_m": np.array([1.0, 2.0])}
        var_names = ("Rho",)
        unit_names = ("normalized",)
        result = convert_fields_to_si(fields, var_names, unit_names)
        assert_allclose(result["rho_m"], [1.0, 2.0])

    def test_convert_fields_applies_factors(self) -> None:
        fields = {"B_1": np.array([5.0])}
        var_names = ("Bx",)
        unit_names = ("nT",)
        result = convert_fields_to_si(fields, var_names, unit_names)
        assert_allclose(result["B_1"], [5e-9], rtol=1e-10)


